"""Real-source eye regression checks. Supports an explicitly reported offline runtime."""
import json, os
from pathlib import Path
from playwright.sync_api import sync_playwright
ROOT=Path(__file__).resolve().parents[2]
BUILD=Path(os.getenv("AEVORA_EYE_BUILD",ROOT/".eye-test-build"))
OUTPUT=Path(os.getenv("AEVORA_EYE_REPORT",ROOT/"docs/eyes-companion-review"));OUTPUT.mkdir(parents=True,exist_ok=True)
HTML=(BUILD/"index.html").read_text().replace('<link rel="stylesheet" href="styles.css">','<style>'+(BUILD/"styles.css").read_text()+'</style>').replace('<script src="bundle.js"></script>','')
BUNDLE=(BUILD/"bundle.js").read_text()
results=[]
def check(condition,name):
    if not condition: raise AssertionError(name)
    results.append(name)
def mood(page,index=0):return page.locator('[data-eye-mood]').nth(index).get_attribute('data-eye-mood')
def event(page,name,detail=None,index=None,bubbles=False):
    page.evaluate("v=>{const target=v.index===null?window:document.querySelectorAll('[data-eye-host]')[v.index];target.dispatchEvent(new CustomEvent(v.name,{detail:v.detail,bubbles:v.bubbles}))}",dict(name=name,detail=detail,index=index,bubbles=bubbles))
def settle(page):page.wait_for_timeout(60)
with sync_playwright() as p:
    browser=p.chromium.launch(executable_path=os.getenv('CHROMIUM_PATH','/usr/bin/chromium'),headless=True,args=['--no-sandbox','--enable-unsafe-swiftshader'])
    page=browser.new_page(viewport={'width':1050,'height':720});errors=[]
    page.on('pageerror',lambda e:errors.append(str(e)))
    page.set_content(HTML);page.add_script_tag(content=BUNDLE)
    page.wait_for_timeout(100)
    if errors: raise AssertionError('Fixture startup: '+str(errors))
    page.wait_for_selector('[data-eye-mood]',timeout=5000);settle(page)
    version=page.evaluate('eyeFixture.reactVersion')
    check(mood(page)=='normal','initial expression is neutral')
    event(page,'orb:mood',{'mood':'heart','duration':300},0,True);settle(page)
    check(mood(page)=='heart' and mood(page,1)=='normal','bubbling host event affects only its own orb')
    page.wait_for_timeout(320)
    check(mood(page)=='normal','transient reaction returns to neutral after its deadline')
    event(page,'orb:mood',{'mood':'happy'});settle(page)
    check(mood(page)=='happy' and mood(page,1)=='happy','existing window mood broadcasts still reach both orbs')
    # Assert the visible SVG state, not only the controller's data attribute.
    page.wait_for_function("[...document.querySelectorAll('.OrbEyes_happyEyesGroup')].every(n=>getComputedStyle(n).opacity==='1')")
    check(page.locator('.OrbEyes_openEyesGroup').evaluate_all("es=>es.every(e=>getComputedStyle(e).opacity==='0')"),'happy expression visibly replaces the open eyes')
    check(page.locator('.OrbEyes_happyEyesGroup').evaluate_all("es=>es.every(e=>getComputedStyle(e).opacity==='1')"),'happy eyelids actually render after their gentle transition')
    for _ in range(20):event(page,'orb:move')
    settle(page);check(mood(page)=='happy','movement event storms do not overwrite deliberate expression')
    event(page,'orb:mood',{'mood':'normal'});settle(page)
    for detail in [None,{'mood':'toString'},{'mood':{}},{'trick':'__proto__'}]:event(page,'orb:mood' if detail is None or 'mood' in detail else 'orb:trick',detail)
    settle(page);check(mood(page)=='normal','malformed and prototype-like custom events are ignored')
    for state,expected in [(1,'curious'),(2,'focused'),(3,'normal'),(0,'content')]:
        page.evaluate('(state)=>eyeFixture.setState(state)',state);settle(page);check(mood(page)==expected,f'existing state {state} produces {expected} eyes')
    page.evaluate("eyeFixture.setMood('wink')");settle(page);event(page,'orb:trick',{'trick':'pet'});settle(page)
    check(mood(page)=='wink','controlled mood takes precedence over automatic reactions')
    page.evaluate("eyeFixture.setMood('normal')");settle(page)
    before=page.evaluate('({...eyeFixture.metrics})')
    page.evaluate("()=>{for(let i=0;i<250;i++)window.dispatchEvent(new PointerEvent('pointermove',{clientX:160+i%40,clientY:150,pointerId:1,isPrimary:true}))}")
    settle(page);after=page.evaluate('({...eyeFixture.metrics})')
    check(after['reads']-before['reads']<=2,'250 synchronous pointer events use at most one layout read per orb')
    check(after['renders']==before['renders'],'gaze tracking does not re-render React')
    transforms=page.locator('.OrbEyes_leftPupil').evaluate_all('(nodes)=>nodes.map(n=>n.style.transform)')
    check(all('translate(' in t and 'NaN' not in t for t in transforms),'gaze writes finite pupil transforms')
    page.evaluate('eyeFixture.setMood(undefined)');settle(page)
    event(page,'orb:mood',{'mood':'normal'});settle(page)
    # Deliberate, frame-separated strokes over the first orb.
    for x in [110,200,110,200,110]:page.mouse.move(x,155);page.wait_for_timeout(45)
    check(mood(page)=='happy','rubbing produces gentle happy eyes without cartoon tricks')
    # Presses only affect the eyes. No body CSS variable is written.
    page.mouse.move(155,155);page.mouse.down();settle(page)
    check(page.locator('[data-eye-host="0"]').evaluate("n=>n.getAttribute('style')===null"),'pressing never changes body styles')
    page.mouse.move(820,510);page.mouse.up();page.wait_for_timeout(230)
    check(page.locator('[data-eye-host="0"]').evaluate("n=>['--ball-hop-y','--ball-squish-x','--ball-squish-y'].every(k=>n.style.getPropertyValue(k)==='')"),'release outside restores original CSS inheritance')
    page.locator('[data-eye-host="0"]').dispatch_event('pointerdown',{'button':2,'pointerId':9,'isPrimary':True})
    check(page.locator('[data-eye-host="0"]').evaluate("n=>n.style.getPropertyValue('--ball-squish-x')")=='' ,'secondary click does not squish the orb')
    page.locator('[data-eye-host="0"]').dispatch_event('pointerdown',{'button':0,'pointerId':9,'clientX':100,'clientY':100,'isPrimary':True})
    page.evaluate("window.dispatchEvent(new PointerEvent('pointercancel',{pointerId:9}))");settle(page)
    check(page.locator('[data-eye-host="0"]').evaluate("n=>n.style.getPropertyValue('--ball-squish-x')")=='' ,'pointercancel restores a pressed orb without a stuck squish')
    # Keyboard activation gets an expression without synthetic body motion.
    event(page,'orb:mood',{'mood':'normal'});settle(page)
    page.get_by_role('button',name='Test eye host 0').focus();page.keyboard.press('Enter');settle(page)
    check(mood(page)=='content','keyboard activation receives eye-only feedback')
    event(page,'orb:mood',{'mood':'normal'});settle(page)
    inactive=page.evaluate("document.getAnimations().filter(a=>/heartPulse|spinSpiral/.test(a.animationName||'')).length")
    check(inactive==0,'hidden heart and spiral expressions do not run animations')
    # Reduced-motion changes apply at runtime, not just on the first mount.
    page.emulate_media(reduced_motion='reduce');settle(page);event(page,'orb:mood',{'mood':'happy'});settle(page)
    check(mood(page)=='happy','reduced-motion mode keeps deliberate emotional feedback')
    check(page.evaluate('document.getAnimations().length')==0,'reduced-motion mode stops all eye animations')
    page.evaluate("Object.defineProperty(document,'hidden',{configurable:true,get:()=>true});document.dispatchEvent(new Event('visibilitychange'))");settle(page)
    check(page.locator('[data-eye-mood]').nth(0).get_attribute('data-paused')=='true','background tab pauses eye work')
    page.evaluate("delete document.hidden;document.dispatchEvent(new Event('visibilitychange'))");page.emulate_media(reduced_motion='no-preference');settle(page)
    page.locator('[data-eye-host="0"]').evaluate("n=>n.dataset.motion='off'");settle(page)
    check(page.locator('[data-eye-mood]').nth(0).get_attribute('data-reduced-motion')=='true','existing desktop motion-off policy also quiets the eyes')
    page.locator('[data-eye-host="0"]').evaluate("n=>{delete n.dataset.motion;n.dataset.animation='suspended'}");settle(page)
    check(page.locator('[data-eye-mood]').nth(0).get_attribute('data-paused')=='true','existing desktop renderer suspension also pauses eye work')
    page.locator('[data-eye-host="0"]').evaluate("n=>delete n.dataset.animation");settle(page)
    event(page,'orb:mood',{'mood':'normal'});settle(page)
    for trick in ['bounce','flip','pet','wink','dizzy']:event(page,'orb:trick',{'trick':trick})
    settle(page);check(mood(page)=='normal','all removed trick events are inert')
    page.evaluate("eyeFixture.setState(2)");page.emulate_media(reduced_motion='reduce');settle(page)
    check(page.locator('.OrbEyes_leftPupil').first.evaluate("n=>{const m=new DOMMatrixReadOnly(getComputedStyle(n).transform);return m.m41===0&&m.m42===0}"),'reduced motion centers gaze even while thinking')
    page.emulate_media(reduced_motion='no-preference');settle(page)
    page.evaluate('eyeFixture.setDialog(true)');page.get_by_role('textbox',name='Focus test').focus()
    page.get_by_role('textbox',name='Focus test').evaluate('n=>n.setSelectionRange(2,5)')
    page.evaluate('eyeFixture.rerender()');settle(page)
    check(page.get_by_role('textbox',name='Focus test').evaluate('n=>document.activeElement===n&&n.selectionStart===2&&n.selectionEnd===5'),'modal rerenders do not steal input focus or caret')
    page.keyboard.press('Escape');settle(page)
    check(page.get_by_role('dialog').count()==0 and page.evaluate('eyeFixture.closedAt')==1,'Escape uses the latest close callback')
    for _ in range(6):
        page.evaluate('eyeFixture.setShown(false)');settle(page)
        check(page.evaluate('eyeFixture.timers.size===0 && eyeFixture.frames.size===0'),'unmount clears eye timers and animation frames')
        page.evaluate('eyeFixture.setShown(true)');settle(page)
    page.evaluate('eyeFixture.unmount()');page.wait_for_timeout(250)
    check(page.evaluate('eyeFixture.timers.size===0 && eyeFixture.frames.size===0'),'root teardown leaves no eye callbacks')
    event(page,'orb:trick',{'trick':'pet'});settle(page)
    check(not errors,'no browser exceptions, including events after teardown')
    report={'reactVersion':version,'browserVersion':browser.version,'fixture':json.loads((BUILD/'metadata.json').read_text()),'passed':len(results),'checks':results,'pointerMetrics':{'before':before,'after':after},'errors':errors}
    (OUTPUT/'eye-browser-results.json').write_text(json.dumps(report,indent=2))
    print(json.dumps({'passed':len(results),'react':version,'errors':errors},indent=2))
    browser.close()
